/// Canonical German labels for grammatical form rows.
///
/// These are the German grammar terms used as row headings in grammar
/// tables throughout the app. Keeping them here avoids scattering
/// hardcoded strings across widget files and makes future updates easy.
abstract final class GrammarDeLabels {
  static const String genitiv = 'Genitiv';
  static const String plural = 'Plural';
  static const String imperfekt = 'Imperfekt';
  static const String perfekt = 'Perfekt';
  static const String komparativ = 'Komparativ';
  static const String superlativ = 'Superlativ';
}

